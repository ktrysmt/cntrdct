CRATES_DOWNLOAD = "https://crates.io/api/v1/crates/{crate}/{version}/download"
SPARSE_INDEX = "https://index.crates.io/{shard}/{crate}"
USER_AGENT = "cntrdct-corpus-fetch/0.1 (https://github.com/ktrysmt/cntrdct)"


def http_get(url: str) -> Tuple[bytes, str]:
    """Return (body, final_url_after_redirects)."""
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as r:  # noqa: S310 — fixed-host
        return r.read(), r.url


def index_shard(crate: str) -> str:
    """The sparse-index sharding rule used by crates.io.
    1-char names live under 1/, 2-char under 2/, 3-char under 3/<first>/,
    and ≥ 4-char names under <first-2>/<chars-3-4>/."""
    n = len(crate)
    if n == 1:
        return "1"
    if n == 2:
        return "2"
    if n == 3:
        return f"3/{crate[0]}"
    return f"{crate[:2]}/{crate[2:4]}"


def lookup_index_cksum(crate: str, version: str) -> str:
    """Fetch the canonical SHA-256 ("cksum") for (crate, version) from
    https://index.crates.io. The response is JSON-lines, one entry per
    published version."""
    url = SPARSE_INDEX.format(shard=index_shard(crate), crate=crate)
    body, _ = http_get(url)
    for line in body.decode("utf-8").strip().split("\n"):
        if not line.strip():
            continue
        entry = json.loads(line)
        if entry.get("vers") == version:
            cksum = entry.get("cksum")
            if not cksum:
                raise RuntimeError(
                    f"index entry for {crate}=={version} has no cksum"
                )
            return cksum
    raise RuntimeError(
        f"version {version} not found in sparse index for crate {crate} "
        f"(checked {url})"
    )


def fetch_crate(entry: CorpusEntry) -> Tuple[bytes, str]:
    """Return (raw_tarball_bytes, final_download_url)."""
    declared = lookup_index_cksum(entry.crate_name, entry.version)
    body, final_url = http_get(
        CRATES_DOWNLOAD.format(crate=entry.crate_name, version=entry.version)
    )
    actual = hashlib.sha256(body).hexdigest()
    if actual != declared:
        raise RuntimeError(
            f"crate hash mismatch for {entry.crate_name}=={entry.version}: "
            f"index says {declared}, downloaded blob is {actual}"
        )
    return body, final_url


def extract_file(tarball: bytes, member_path: str) -> bytes:
    with tarfile.open(fileobj=io.BytesIO(tarball), mode="r:gz") as tf:
        try:
            f = tf.extractfile(member_path)
        except KeyError:
            f = None
        if f is None:
            raise RuntimeError(f"member not found in tarball: {member_path}")
        body = f.read()
    # Reject files that announce themselves as auto-generated. Such
    # files produce noise rather than signal in the cntrdct scan
    # (every method is structurally identical, so clone-drift fires
    # for every pair). A `// @generated` or `# @generated` marker in
    # the first 200 bytes is the de facto convention (syn, prost,
    # protobuf-rust, tonic, etc. all emit it).
    head = body[:200].lower()
    if b"@generated" in head:
        raise RuntimeError(
            f"member {member_path} carries an @generated marker; "
            "remove it from CORPUS or the resulting findings will "
            "be FPs by construction"
        )
    return body


def write_with_header(
    out_path: Path, body: bytes, source_url: str, license_spdx: str
) -> str:
    """Prepend a provenance header to `body` and write to `out_path`.
    Returns the SHA-256 of the written file (header + body).

    Rust line-comment syntax `//` is used so the cntrdct parser
    accepts the file. Mirroring the Python fetcher's `#` would
    produce a syntax error and the scanner would silently drop
    the file."""
    header = (
        f"// Source: {source_url}\n"
        f"// License: {license_spdx}\n"
        f"// Note: verbatim extract from upstream .crate\n"
        f"\n"
    )
    composed = header.encode("utf-8") + body
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(composed)
    return hashlib.sha256(composed).hexdigest()


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default="benchmarks/wild-corpus",
        help="output directory (default: benchmarks/wild-corpus)",
    )
    parser.add_argument(
        "--manifest-skeleton",
        action="store_true",
        help=(
            "in addition to fetching files, write a manifest skeleton "
            "to <out>/manifest.skeleton.jsonl with empty `expected` arrays. "
            "Maintainer triages cntrdct findings into the real "
            "manifest.jsonl by hand."
        ),
    )
    args = parser.parse_args(argv[1:])

    out_root = Path(args.out)
    files_dir = out_root / "files"
    files_dir.mkdir(parents=True, exist_ok=True)

    skeleton: List[dict] = []
    for entry in CORPUS:
        print(f"fetching {entry.crate_name}=={entry.version}", file=sys.stderr)
        tarball, source_url = fetch_crate(entry)
        for member_path, flat_name in entry.files:
            try:
                body = extract_file(tarball, member_path)
            except RuntimeError as e:
                print(f"  skipping {flat_name}: {e}", file=sys.stderr)
                continue
            out_path = files_dir / flat_name
            sha = write_with_header(out_path, body, source_url, entry.license)
            print(f"  wrote files/{flat_name} sha256={sha[:12]}…", file=sys.stderr)
            skeleton.append(
                {
                    "file": f"files/{flat_name}",
                    "expected": [],
                    "source": source_url,
                    "license": entry.license,
                    "sha256": sha,
                }
            )

    if args.manifest_skeleton:
        skel_path = out_root / "manifest.skeleton.jsonl"
        with skel_path.open("w") as f:
            f.write(
                "// Manifest skeleton for the P-1 Rust wild corpus.\n"
                "// Generated by scripts/fetch_rust_corpus.py.\n"
                "// Maintainer fills in `expected: [...]` per file by\n"
                "// running `cntrdct scan` and triaging findings.\n"
            )
            for row in skeleton:
                f.write(json.dumps(row, sort_keys=True) + "\n")
        print(f"wrote {skel_path}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

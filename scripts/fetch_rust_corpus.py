#!/usr/bin/env python3
"""
Fetch a curated set of Rust source files from crates.io and lay them
out under benchmarks/wild-corpus/ for the P-1 Rust wild corpus.

Each entry in CORPUS pins (crate_name, version, license_spdx, [files]).
For each entry the script:
  1. Looks up the canonical SHA-256 ("cksum") for that release in the
     sparse index at https://index.crates.io/<shard>/<crate>.
  2. Downloads the .crate tarball from
     https://crates.io/api/v1/crates/<crate>/<version>/download (which
     redirects to https://static.crates.io/crates/...). The script
     records the FINAL URL so provenance is unambiguous.
  3. Verifies the SHA-256 of the tarball against the value the sparse
     index reports. A mismatch is a hard fail.
  4. Extracts the listed `files` paths into
     benchmarks/wild-corpus/files/<flat_name>.rs.
  5. Prepends a 3-line provenance comment block (`// Source:`,
     `// License:`, `// Note:`) so the corpus is auditable. Rust
     line-comment syntax (NOT Python's `#`) is required so the
     cntrdct parser accepts the file.
  6. Emits / refreshes a manifest skeleton with `source`, `license`,
     `sha256` filled in. The maintainer fills in `expected: [...]`
     afterwards by running `cntrdct scan` and triaging findings.

Re-running the script is idempotent: the file content (header + body)
and recorded SHA-256 are deterministic for a pinned (crate, version,
file_path) triple. CI can therefore call this script and `git diff`
to detect drift.

Usage:
  python3 scripts/fetch_rust_corpus.py [--out benchmarks/wild-corpus] \\
      [--manifest-skeleton]

Environment:
  Network access to https://crates.io and https://index.crates.io. No
  third-party Python deps; uses stdlib `urllib`, `tarfile`, `hashlib`,
  `json`.
"""

